function fixedRandom(values) {
  let index = 0;
  return () => {
    const value = values[index % values.length];
    index += 1;
    return value;
  };
}

function fakeEvent(heads, speed = CONFIG.OBSTACLE_START_SPEED) {
  return {
    type: heads.length === 1 ? "single" : "double",
    speed,
    threatening: true,
    collided: false,
    heads: heads.map((head) => createTestHead(head.x, head.y, head.type ?? HEAD_TYPE))
  };
}

function fakeEventFromObstacles(heads, speed = CONFIG.OBSTACLE_START_SPEED) {
  return {
    type: heads.length === 1 ? "single" : "double",
    speed,
    threatening: true,
    collided: false,
    heads
  };
}

