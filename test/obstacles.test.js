function midpoint(a, b) {
  return a + (b - a) / 2;
}

function assertAlmostEqual(actual, expected, epsilon = 1e-9) {
  assert.ok(Math.abs(actual - expected) <= epsilon, `${actual} did not equal ${expected}`);
}

function sampleScheduledEvents() {
  const scheduler = new DeterministicObstacleScheduler();
  const events = [];
  for (let i = 0; i < 4; i += 1) {
    const event = scheduler.nextEvent({
      difficultyStage: 0,
      surferY: 300,
      activeHeads: []
    });
    events.push({
      patternId: event.patternId,
      heads: event.heads.map((head) => [head.obstacleTypeId, head.row, head.timeOffset])
    });
  }
  return events;
}

